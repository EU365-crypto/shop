const express = require('express');
const { DatabaseSync } = require('node:sqlite');
const bcrypt = require('bcryptjs');
const { sessionConfig, installSessions, logoutSession } = require('../../src/auth/session-security');
const { registerPasswordAuthentication } = require('../../src/auth/password-authentication');
const { registerCatalog } = require('../../src/catalog/catalog');
const db = new DatabaseSync(process.argv[2]);
db.exec('CREATE TABLE IF NOT EXISTS users(id INTEGER PRIMARY KEY,email TEXT,password_hash TEXT,role TEXT,email_verified INTEGER)');
const hash = bcrypt.hashSync('catalog-test-password', 4);
for (const [id, role] of [[1, 'admin'], [2, 'user']]) db.prepare('INSERT OR IGNORE INTO users VALUES(?,?,?,?,1)').run(id, role + '@example.test', hash, role);
const app = express(); app.use(express.json());
const config = sessionConfig({ NODE_ENV: 'test', SESSION_SECRET: '59c3a8b2706f1d4ea901c784b2d8e351ac792f6b0e8d134a58c207d936a45bef', BASE_URL: 'http://localhost:3000' });
installSessions(app, db, req => req.path.startsWith('/api/admin') || req.path.startsWith('/api/catalog/') || req.query.admin === '1', config);
registerPasswordAuthentication(app, db, () => {}, async () => {});
registerCatalog(app, db);
app.get('/api/me', (req,res) => { req.session.guestId ||= 'test-guest'; res.json({ loggedIn: Boolean(req.session.user), user: req.session.user, guestId: req.session.guestId }); });
app.post('/api/logout', (req,res,next) => logoutSession(req,res,next,config));
const server=app.listen(0,'127.0.0.1',()=>process.send({url:`http://127.0.0.1:${server.address().port}`}));
process.on('message', message => { if (message === 'close') server.close(()=>{db.close();process.exit(0);}); });
